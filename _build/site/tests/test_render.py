def fake_pictures(code: str) -> dict[str, Picture]:
    pictures = {key: Picture(f"/artwidget/assets/img/{key}-1.webp",
                             f"/artwidget/assets/img/{key}-1.webp 1w, /artwidget/assets/img/{key}-2.webp 2w", 1, 2)
                for key in ("icon", "starry", "pearl", "shot_widget", "shot_details", "shot_settings")}
    pictures["badge"] = Picture(f"/assets/badges/{code}.png", "", 646, 250)
    return pictures


class Tags(HTMLParser):
    def __init__(self, html: str):
        super().__init__()
        self.tags: list[tuple[str, dict]] = []
        self.feed(html)

    def handle_starttag(self, tag, attrs):
        self.tags.append((tag, dict(attrs)))

    def find(self, tag: str, **attrs) -> list[dict]:
        return [a for t, a in self.tags if t == tag and all(a.get(k) == v for k, v in attrs.items())]


def render(lang=EN, strings=STRINGS) -> str:
    return render_page(ART_WIDGET, lang, strings, fake_pictures(lang.code), video=VIDEO_URL, poster=POSTER_URL,
                       commons=COMMONS_PAGES)


class RenderTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.html = render()
        cls.tags = Tags(cls.html)

    def test_head_en(self):
        self.assertTrue(self.html.startswith("<!doctype html>"))
        self.assertIn("Generated by _build/site/build.py from apps/artwidget/template.html", self.html)
        self.assertIn('<html lang="en">', self.html)
        self.assertIn("<title>Art Widget: Artwork of the Day</title>", self.html)
        self.assertEqual([a["href"] for a in self.tags.find("link", rel="canonical")],
                         ["https://forio-dk.github.io/artwidget/"])

    def test_hreflang(self):
        alternates = {(a["hreflang"], a["href"]) for a in self.tags.find("link", rel="alternate")}
        expected = {(lang.code, page_url(ART_WIDGET, lang)) for lang in LANGS}
        expected.add(("x-default", "https://forio-dk.github.io/artwidget/"))
        self.assertEqual(alternates, expected)

    def test_json_ld(self):
        blocks = re.findall(r'<script type="application/ld\+json">(.*?)</script>', self.html, re.S)
        self.assertEqual(len(blocks), 1)
        data = json.loads(blocks[0])
        self.assertEqual(data["@type"], "MobileApplication")
        self.assertEqual(data["offers"]["price"], "0")
        self.assertEqual(data["installUrl"], play_url(ART_WIDGET, EN))
        self.assertNotIn("aggregateRating", json.dumps(data))

    def test_play_links(self):
        self.assertEqual(len(self.tags.find("a", href=play_url(ART_WIDGET, EN))), 2)
        self.assertIn("&amp;referrer=", self.html)

    def test_privacy_link(self):
        self.assertIn('href="/artwidget/privacy-policy.html" hreflang="en"', self.html)

    def test_no_third_party_src(self):
        self.assertEqual(re.findall(r'(?:src|srcset|poster)="https?:', self.html), [])

    def test_video_lazy(self):
        self.assertIn('preload="none"', self.html)
        self.assertIn('poster="/artwidget/assets/video/preview-poster.webp"', self.html)

    def test_no_javascript(self):
        self.assertEqual(self.html.count("<script"), 1)
        self.assertEqual(len(self.tags.find("script", type="application/ld+json")), 1)

    def test_ru_specifics(self):
        html = render(RU)
        tags = Tags(html)
        self.assertIn('<html lang="ru">', html)
        self.assertEqual(len(tags.find("link", rel="preload",
                                       href="/assets/fonts/playfair-display-cyrillic-600-normal.woff2")), 1)
        self.assertEqual(len(tags.find("img", src="/assets/badges/ru.png")), 2)
        self.assertEqual(len(tags.find("a", href=play_url(ART_WIDGET, RU))), 2)
        self.assertIn("hl=ru", play_url(ART_WIDGET, RU))

    def test_footer_languages(self):
        footer = Tags(self.html.split("<footer", 1)[1])
        links = [a for t, a in footer.tags if t == "a" and "lang" in a]
        self.assertEqual(len(links), 6)
        self.assertEqual([a["lang"] for a in links if a.get("aria-current") == "page"], ["en"])

    def test_escaping(self):
        strings = copy.deepcopy(STRINGS)
        strings["hero"]["lead"] = "<b>x</b>"
        self.assertIn("&lt;b&gt;x&lt;/b&gt;", render(strings=strings))

    def test_missing_string_fails(self):
        strings = copy.deepcopy(STRINGS)
        del strings["hero"]["lead"]
        with self.assertRaises(UndefinedError):
            render(strings=strings)

    def test_stylesheets(self):
        self.assertEqual([a["href"] for a in self.tags.find("link", rel="stylesheet")],
                         ["/assets/site.css", "/artwidget/assets/theme.css"])
        self.assertEqual([a["href"] for a in self.tags.find("link", rel="preload")],
                         ["/assets/fonts/playfair-display-latin-600-normal.woff2"])

    def test_hero_image_high_priority(self):
        starry = [a for a in self.tags.find("img") if a["src"].startswith("/artwidget/assets/img/starry")]
        self.assertEqual(len(starry), 1)
        self.assertEqual(starry[0].get("fetchpriority"), "high")
        self.assertNotIn("loading", starry[0])


