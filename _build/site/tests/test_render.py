def art(name: str) -> str:
    return f"/syllabee/assets/img/art/{name}.svg"


def render_syllabee(code: str = "en", strings: dict | None = None,
                    syllables: tuple[str, ...] = ("BA", "NA", "NA")) -> str:
    pictures = {key: fake(f"/syllabee/assets/img/{code}/{key.replace('_', '-')}-200.webp") for key in SYLLABEE_KEYS}
    pictures["icon"] = fake("/syllabee/assets/img/icon-64.webp")
    pictures["badge"] = Picture(f"/assets/badges/{code}.png", "", 646, 250)
    themes = [Tile(key, art(name), "#123456", key in FULL_THEMES) for key, name in THEMES.items()]
    colouring = [Tile(key, art(name), "#654321", False) for key, name in COLOURING.items()]
    return render_page(SYLLABEE, SYLLABEE_LANGS[code], strings or load_strings([code], SYLLABEE.strings)[code],
                       pictures, syllables=syllables, cards=[art(name) for name in CARDS], themes=themes,
                       colouring=colouring, video=f"/syllabee/assets/video/{code}.mp4",
                       poster=f"/syllabee/assets/video/{code}-poster.webp")


