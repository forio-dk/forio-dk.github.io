class Headings(HTMLParser):
    """The text of every <h2>."""

    def __init__(self, html: str):
        super().__init__()
        self.h2: list[str] = []
        self.inside = False
        self.feed(html)

    def handle_starttag(self, tag, attrs):
        if tag == "h2":
            self.inside = True
            self.h2.append("")

    def handle_endtag(self, tag):
        if tag == "h2":
            self.inside = False

    def handle_data(self, data):
        if self.inside:
            self.h2[-1] += data.strip()


