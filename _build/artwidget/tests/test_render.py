class Headings(HTMLParser):
    """The text of every <h2>."""

    def __init__(self, html: str):
        super().__init__()
        self.h2: list[str] = []
        self.inside = False
        self.feed(html)

    def handle_starttag(self, tag, attrs):
        if tag == "h2":
            self.inside = True
            self.h2.append("")

    def handle_endtag(self, tag):
        if tag == "h2":
            self.inside = False

    def handle_data(self, data):
        if self.inside:
            self.h2[-1] += data.strip()


class HomeTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        pictures = {key: Picture(f"/artwidget/assets/img/apps/{key}-96.webp",
                                 f"/artwidget/assets/img/apps/{key}-96.webp 96w", 96, 96)
                    for key in ("art_widget", "atlas_hunt", "syllabee", "forio")}
        cls.html = render_home(pictures)
        cls.tags = Tags(cls.html)

    def test_head(self):
        self.assertTrue(self.html.startswith("<!doctype html>"))
        self.assertIn("Generated by _build/artwidget/build.py", self.html)
        self.assertIn('<html lang="en">', self.html)
        self.assertIn("<title>Forio: Android apps</title>", self.html)
        self.assertEqual([a["href"] for a in self.tags.find("link", rel="canonical")], ["https://forio-dk.github.io/"])
        self.assertNotIn('http-equiv="refresh"', self.html)

    def test_cards(self):
        self.assertEqual(Headings(self.html).h2, ["Art Widget", "Atlas Hunt", "Syllabee"])
        for text in DESCRIPTIONS:
            self.assertIn(text, self.html)

    def test_links(self):
        hrefs = {a["href"] for a in self.tags.find("a")} - {"mailto:forio.dk@gmail.com"}
        self.assertEqual(hrefs, {"/artwidget/", "/artwidget/privacy-policy.html", "/atlashunt/privacy-policy.html",
                                 "/syllabee/privacy-policy.html"})
        self.assertNotIn("play.google.com", self.html)
        self.assertEqual(self.html.count('<p class="soon">Coming soon</p>'), 2)

    def test_no_javascript(self):
        self.assertNotIn("<script", self.html)

    def test_logo(self):
        self.assertEqual([a["href"] for a in self.tags.find("link", rel="icon")], ["/favicon.ico"])
        self.assertEqual([a["href"] for a in self.tags.find("link", rel="apple-touch-icon")], ["/apple-touch-icon.png"])
        self.assertEqual(len(self.tags.find("img", src="/artwidget/assets/img/apps/forio-96.webp")), 1)
